/**
 * Which representation of the source a pattern runs against:
 * - `code`: comments and string contents masked (structure only)
 * - `text`: comments masked, string contents intact
 * - `raw`:  untouched source, comments included
 */
export type PatternView = "code" | "text" | "raw";

export interface PatternRule extends RuleMeta {
  pattern: RegExp;
  view: PatternView;
  confidence: number;
  /** Extra guard evaluated against the full matched line (text view). */
  where?: (line: string) => boolean;
}

type Spec = Omit<PatternRule, "detector" | "description" | "remediation"> & {
  description: string;
  remediation: string;
};

const r = (s: Spec): PatternRule => ({ ...s, detector: "pattern" });

const JS: Language[] = ["javascript", "typescript"];
const SECURITY_CONTEXT = /token|secret|passw|salt|nonce|otp|session|csrf|api.?key|credential|reset|invite/i;

function rules(
  languages: Language[] | "*",
  category: FindingCategory,
  list: Array<Omit<Spec, "languages" | "category"> & { category?: FindingCategory; languages?: Language[] | "*" }>
): PatternRule[] {
  return list.map((s) => r({ languages, category, ...s }));
}

